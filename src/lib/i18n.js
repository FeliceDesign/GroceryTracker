const DICTS = { de: DE, en: EN };

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
}

function lookup(dict, key) {
  return key.split('.').reduce((o, k) => (o && o[k] != null ? o[k] : undefined), dict);
}

// `lang` wird als expliziter Prop gereicht (wie `t`/`dark`), damit keine
// neue Context-Konvention nötig ist. Fällt bei fehlendem Key aufs deutsche
// Wörterbuch zurück, zuletzt auf den Key selbst (nie ein leerer String).
export function tr(lang, key, vars) {
  const dict = DICTS[lang] || DE;
  const val = lookup(dict, key);
  if (val == null) return lookup(DE, key) ?? key;
  return interpolate(val, vars);
}

